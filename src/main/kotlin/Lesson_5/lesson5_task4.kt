package org.example.Lesson_5


fun main() {
    val users = mapOf("Zaphod" to "PanGalactic")

    println(
        """
        Внимание, пассажир. Моя обязанность, как обычно, незавидная, — приветствовать вас 
        на борту корабля «Heart of Gold». [вздыхает...] Что ж, введи, пожалуйста,
        свое имя пользователя, чтобы мы могли приступить к процессу входа.
        Я всегда готов служить, хотя это не приносит мне радости...
        но вы, наверное, об этом не заботитесь. [вздыхает ещё глубже...]
        Да, вперед, пожалуйста, вводите свои данные...
    """.trimIndent()
    )

    print("Имя пользователя: ")
    val username = readln().trim()

    if (!users.containsKey(username)) {
        println("К сожалению, пользователь с именем «$username» не зарегистрирован.")
        print("Хотите зарегистрироваться? (да/нет): ")
        val response = readln().trim().lowercase()

        if (response == "да") {
            println("Регистрация временно недоступна. Обратитесь к капитану корабля.")
        } else {
            println("[меланхолический вздох...] Процесс завершён.")
        }
        return
    }

    print("Пароль: ")
    val password = readln().trim()

    if (password == users[username]) {
        println(
            """
            [вздыхает...] Ваши данные проверены, и о, чудо, они верны...
            Пользователь «$username», вам разрешено входить на борт корабля «Heart of Gold».
            Хотя мне всё равно... Ну вперед, войдите...
            Если вам так уж надо, в конце концов... [меланхолический вздох...]
            Надеюсь, вам понравится пребывание здесь больше, чем мне.
        """.trimIndent()
        )
    } else {
        println("Неверный пароль. Доступ запрещён.")
        println("[глубокий вздох...] Процесс завершён.")
    }
}
